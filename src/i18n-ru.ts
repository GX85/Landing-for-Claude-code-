let table: Map<string, string> | undefined;

const norm = (s: string) => s.replace(/\s+/g, " ").trim();

/** Translates one line of interface text into Russian; unknown lines come back unchanged. */
export function translateRu(text: string): string {
  const key = norm(text);
  if (!key) return text;
  table ??= new Map(PAIRS.map(([en, ru]) => [norm(en), ru]));
  const hit = table.get(key);
  if (hit !== undefined) return hit;
  for (const [re, fn] of RULES) {
    const m = re.exec(key);
    if (m) return fn(m, translateRu);
  }
  return text;
}
